import 'dart:convert';

/// A single mutation in an atomic document batch.
///
/// Use [BatchWriteDocumentOperation.create], [update], or [delete] so the
/// operation contains exactly the fields required by the backend contract.
class BatchWriteDocumentOperation {
  static const int maximumKeyLength = 200;
  static const int maximumPayloadBytes = 1024 * 1024;

  final BatchWriteOperationType type;
  final String? key;
  final Map<String, dynamic>? data;
  final String? documentId;
  final int? expectedVersion;

  const BatchWriteDocumentOperation._({
    required this.type,
    this.key,
    this.data,
    this.documentId,
    this.expectedVersion,
  });

  /// Creates a new document. The document ID is generated by the server.
  factory BatchWriteDocumentOperation.create({
    required String key,
    required Map<String, dynamic> data,
  }) {
    return BatchWriteDocumentOperation._(
      type: BatchWriteOperationType.create,
      key: key,
      data: data,
    );
  }

  /// Replaces an existing document using optimistic concurrency.
  factory BatchWriteDocumentOperation.update({
    required String documentId,
    required String key,
    required Map<String, dynamic> data,
    required int expectedVersion,
  }) {
    return BatchWriteDocumentOperation._(
      type: BatchWriteOperationType.update,
      documentId: documentId,
      key: key,
      data: data,
      expectedVersion: expectedVersion,
    );
  }

  /// Soft-deletes an existing document using optimistic concurrency.
  factory BatchWriteDocumentOperation.delete({
    required String documentId,
    required int expectedVersion,
  }) {
    return BatchWriteDocumentOperation._(
      type: BatchWriteOperationType.delete,
      documentId: documentId,
      expectedVersion: expectedVersion,
    );
  }

  /// Validates this operation and returns its backend JSON representation.
  Map<String, dynamic> toJson() {
    final result = <String, dynamic>{'type': type.name};

    switch (type) {
      case BatchWriteOperationType.create:
        result['key'] = _normalizeKey(key);
        result['data'] = _validatedData(data);
        break;
      case BatchWriteOperationType.update:
        result['documentId'] = _normalizeId(documentId, 'documentId');
        result['key'] = _normalizeKey(key);
        result['data'] = _validatedData(data);
        result['expectedVersion'] = _validateVersion(expectedVersion);
        break;
      case BatchWriteOperationType.delete:
        result['documentId'] = _normalizeId(documentId, 'documentId');
        result['expectedVersion'] = _validateVersion(expectedVersion);
        break;
    }

    return result;
  }

  /// UTF-8 size of the operation's JSON data payload, matching the backend's
  /// aggregate payload limit. Delete operations contribute zero bytes.
  int get dataPayloadBytes {
    if (data == null) return 0;
    return utf8.encode(jsonEncode(_validatedData(data))).length;
  }

  static String _normalizeKey(String? value) {
    final normalized = value?.trim();
    if (normalized == null || normalized.isEmpty) {
      throw ArgumentError.value(value, 'key', 'Cannot be empty.');
    }
    if (normalized.length > maximumKeyLength ||
        _containsControlCharacters(normalized)) {
      throw ArgumentError.value(
        value,
        'key',
        'Must not exceed $maximumKeyLength characters or contain control characters.',
      );
    }
    return normalized;
  }

  static String _normalizeId(String? value, String name) {
    final normalized = value?.trim();
    if (normalized == null || normalized.isEmpty) {
      throw ArgumentError.value(value, name, 'Cannot be empty.');
    }
    return normalized;
  }

  static int _validateVersion(int? value) {
    if (value == null || value < 1) {
      throw ArgumentError.value(
        value,
        'expectedVersion',
        'Must be a positive integer.',
      );
    }
    return value;
  }

  static Map<String, dynamic> _validatedData(Map<String, dynamic>? value) {
    if (value == null) {
      throw ArgumentError.value(value, 'data', 'Cannot be null.');
    }

    try {
      final decoded = jsonDecode(jsonEncode(value));
      if (decoded is! Map<String, dynamic>) {
        throw const FormatException('Document data must be a JSON object.');
      }
      return decoded;
    } on JsonUnsupportedObjectError catch (error) {
      throw FormatException('Document data is not JSON serializable: $error');
    }
  }

  static bool _containsControlCharacters(String value) =>
      value.contains(RegExp(r'[\x00-\x1F\x7F]'));
}

/// Operation names used by the Mebabl Database batch API.
enum BatchWriteOperationType { create, update, delete }
